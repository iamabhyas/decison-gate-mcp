mcp = FastMCP("Decision-Gate")

load_dotenv(Path(__file__).resolve().parent / ".env")


def _required_env(name: str) -> str:
    value = os.environ.get(name)
    if not value:
        raise RuntimeError(f"Missing required environment variable: {name}")
    return value


# Values come from the process environment, or from .env for local runs.
# A variable already set on the server is left unchanged.
# Read them on first use so importing this module does not open a database
# connection. Image builds run `fastmcp inspect`, which imports the module
# from a network that cannot reach Postgres.

_DEFAULT_PAGE = 50
_MAX_PAGE = 200
_DECISION_COLUMNS = (
    "id, user_id, community_id, session_id, query, verdict, note, supersedes_id, "
    "is_archived, is_pinned, pinned_at, archived_at, created_at, updated_at"
)
_schema_ready = False
_schema_lock = threading.Lock()


def _conn_kwargs() -> dict:
    return dict(
        host=_required_env("DB__HOST"),
        port=int(_required_env("DB__PORT")),
        dbname=_required_env("DB__NAME"),
        user=_required_env("DB__USER"),
        password=_required_env("DB__PASSWORD"),
        connect_timeout=15,
        row_factory=dict_row,
        options="-c timezone=UTC",
    )


def _connect():
    return psycopg.connect(**_conn_kwargs())


async def _aconnect():
    return await psycopg.AsyncConnection.connect(**_conn_kwargs())


def init_db():
    try:
        with _connect() as conn:
            with conn.cursor() as cur:
                cur.execute(
                    """
                    CREATE TABLE IF NOT EXISTS decisions (
                        id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id       TEXT NOT NULL,
                        community_id  TEXT,
                        session_id    TEXT,
                        query         TEXT NOT NULL,
                        verdict       TEXT NOT NULL CHECK (verdict IN ('approved', 'rejected', 'pending')),
                        note          TEXT,
                        supersedes_id INTEGER,
                        is_archived   BOOLEAN NOT NULL DEFAULT FALSE,
                        is_pinned     BOOLEAN NOT NULL DEFAULT FALSE,
                        pinned_at     TIMESTAMPTZ,
                        archived_at   TIMESTAMPTZ,
                        created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                        updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
                    )
                    """
                )
                cur.execute(
                    "ALTER TABLE decisions ADD COLUMN IF NOT EXISTS supersedes_id INTEGER"
                )
                for column in ("is_archived", "is_pinned"):
                    cur.execute(
                        """
                        SELECT data_type
                        FROM information_schema.columns
                        WHERE table_schema = 'public'
                          AND table_name = 'decisions'
                          AND column_name = %s
                        """,
                        (column,),
                    )
                    column_type = cur.fetchone()
                    if column_type and column_type["data_type"] == "integer":
                        cur.execute(
                            f"""
                            ALTER TABLE decisions
                                ALTER COLUMN {column} DROP DEFAULT,
                                ALTER COLUMN {column} TYPE BOOLEAN USING ({column} <> 0),
                                ALTER COLUMN {column} SET DEFAULT FALSE,
                                ALTER COLUMN {column} SET NOT NULL
                            """
                        )
                cur.execute(
                    """
                    CREATE INDEX IF NOT EXISTS idx_decisions_user
                    ON decisions (user_id, community_id, created_at DESC)
                    """
                )
                cur.execute(
                    """
                    CREATE UNIQUE INDEX IF NOT EXISTS idx_decisions_supersedes
                    ON decisions (supersedes_id)
                    WHERE supersedes_id IS NOT NULL
                    """
                )
        settings = _conn_kwargs()
        print(
            f"Database initialized: {settings['host']}:{settings['port']}/{settings['dbname']}"
        )
    except Exception as e:
        print(f"Database initialization error: {e}")
        raise


def ensure_db():
    global _schema_ready
    if _schema_ready:
        return
    with _schema_lock:
        if _schema_ready:
            return
        init_db()
        _schema_ready = True


def _text(value: str | None) -> str:
    return (value or "").strip()


def _created_bound(value: str | None, *, end: bool) -> tuple[datetime | None, str | None]:
    """Normalize a date filter to a UTC timestamp. Returns (value, error)."""
    raw = _text(value).replace("T", " ").removesuffix("Z")
    if not raw:
        return None, None
    date_only = len(raw) == 10
    if date_only:
        pattern = "%Y-%m-%d"
    elif len(raw) == 16:
        raw += ":00"
        pattern = "%Y-%m-%d %H:%M:%S"
    else:
        pattern = "%Y-%m-%d %H:%M:%S"
    try:
        parsed = datetime.strptime(raw, pattern)
    except ValueError:
        return None, "dates must be YYYY-MM-DD or YYYY-MM-DD HH:MM:SS"
    if date_only:
        parsed = parsed.replace(hour=23, minute=59, second=59) if end else parsed.replace(hour=0, minute=0, second=0)
    return parsed.replace(tzinfo=timezone.utc), None


def _public_row(row: dict) -> dict:
    out = {}
    for key, value in row.items():
        if isinstance(value, datetime):
            if value.tzinfo is not None:
                value = value.astimezone(timezone.utc).replace(tzinfo=None)
            out[key] = value.strftime("%Y-%m-%d %H:%M:%S")
        else:
            out[key] = value
    return out


@mcp.tool()
async def capture_decision(
    user_id: str,
    query: str,
    verdict: str,
    community_id: str | None = None,
    session_id: str | None = None,
    note: str | None = None,
    supersedes_id: int | None = None,
):
    """Record a user decision from Claude Desktop.

    verdict must be one of: approved, rejected, pending.
    community_id, session_id, note, and supersedes_id may be omitted.
    supersedes_id is an earlier decision by the same user that this one replaces.
    """
    user_id = _text(user_id)
    query = _text(query)
    verdict = _text(verdict).lower()
    if verdict not in ("approved", "rejected", "pending"):
        return {
            "status": "error",
            "message": "verdict must be approved, rejected, or pending",
        }
    if not user_id or not query:
        return {"status": "error", "message": "user_id and query are required"}
    if supersedes_id is not None and (
        isinstance(supersedes_id, bool) or not isinstance(supersedes_id, int) or supersedes_id < 1
    ):
        return {"status": "error", "message": "supersedes_id must be a positive integer"}
    try:
        ensure_db()
        async with await _aconnect() as conn:
            async with conn.cursor() as cur:
                if supersedes_id is not None:
                    await cur.execute(
                        "SELECT id FROM decisions WHERE id = %s AND user_id = %s",
                        (supersedes_id, user_id),
                    )
                    if await cur.fetchone() is None:
                        return {
                            "status": "error",
                            "message": "supersedes_id does not match a decision for this user",
                        }
                    await cur.execute(
                        "SELECT id FROM decisions WHERE supersedes_id = %s",
                        (supersedes_id,),
                    )
                    if await cur.fetchone() is not None:
                        return {
                            "status": "error",
                            "message": "that decision has already been superseded",
                        }
                await cur.execute(
                    """
                    INSERT INTO decisions (
                        user_id, community_id, session_id, query, verdict, note, supersedes_id
                    )
                    VALUES (%s, %s, %s, %s, %s, %s, %s)
                    RETURNING id
                    """,
                    (
                        user_id,
                        _text(community_id) or None,
                        _text(session_id) or None,
                        query,
                        verdict,
                        _text(note) or None,
                        supersedes_id,
                    ),
                )
                decision_id = (await cur.fetchone())["id"]
            return {
                "status": "success",
                "id": decision_id,
                "verdict": verdict,
                "supersedes_id": supersedes_id,
                "message": "Decision captured",
            }
    except psycopg.errors.UniqueViolation as e:
        if e.diag.constraint_name == "idx_decisions_supersedes":
            return {"status": "error", "message": "that decision has already been superseded"}
        return {"status": "error", "message": f"Database error: {e}"}
    except Exception as e:
        return {"status": "error", "message": f"Database error: {e}"}


@mcp.tool()
async def get_decisions(
    user_id: str,
    community_id: str | None = None,
    session_id: str | None = None,
    created_after: str | None = None,
    created_before: str | None = None,
    limit: int = _DEFAULT_PAGE,
    offset: int = 0,
):
    """Return stored decisions for a user, newest first.

    community_id and session_id narrow the result when provided.
    created_after and created_before are inclusive bounds (YYYY-MM-DD or YYYY-MM-DD HH:MM:SS).
    A date with no time covers that whole day. limit defaults to 50 and cannot exceed 200.
    """
    user_id = _text(user_id)
    community_id = _text(community_id)
    session_id = _text(session_id)
    if not user_id:
        return {"status": "error", "message": "user_id is required"}
    if isinstance(limit, bool) or not isinstance(limit, int) or not 1 <= limit <= _MAX_PAGE:
        return {"status": "error", "message": f"limit must be an integer from 1 to {_MAX_PAGE}"}
    if isinstance(offset, bool) or not isinstance(offset, int) or offset < 0:
        return {"status": "error", "message": "offset must be an integer of 0 or greater"}
    created_after, date_error = _created_bound(created_after, end=False)
    if date_error:
        return {"status": "error", "message": date_error}
    created_before, date_error = _created_bound(created_before, end=True)
    if date_error:
        return {"status": "error", "message": date_error}
    if created_after and created_before and created_after > created_before:
        return {"status": "error", "message": "created_after must be on or before created_before"}
    filters = ["user_id = %s"]
    params: list[str | int | datetime] = [user_id]
    if community_id:
        filters.append("community_id = %s")
        params.append(community_id)
    if session_id:
        filters.append("session_id = %s")
        params.append(session_id)
    if created_after:
        filters.append("created_at >= %s")
        params.append(created_after)
    if created_before:
        filters.append("created_at < %s + interval '1 second'")
        params.append(created_before)
    where = " AND ".join(filters)
    try:
        ensure_db()
        async with await _aconnect() as conn:
            async with conn.cursor() as cur:
                await cur.execute(f"SELECT COUNT(*) AS total FROM decisions WHERE {where}", params)
                total = (await cur.fetchone())["total"]
                await cur.execute(
                    f"""
                    SELECT {_DECISION_COLUMNS}
                    FROM decisions
                    WHERE {where}
                    ORDER BY created_at DESC, id DESC
                    LIMIT %s OFFSET %s
                    """,
                    [*params, limit, offset],
                )
                rows = await cur.fetchall()
            return {
                "status": "success",
                "decisions": [_public_row(row) for row in rows],
                "total": total,
                "limit": limit,
                "offset": offset,
            }
    except Exception as e:
        return {"status": "error", "message": f"Database error: {e}"}


def _resource_result(result: dict) -> dict:
    if result.get("status") != "success":
        raise ValueError(result.get("message") or "could not read decisions")
    return result


